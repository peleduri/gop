func TestRenderEscapes(t *testing.T) {
	now := time.Date(2026, 11, 20, 10, 0, 0, 0, time.UTC)
	g := &graph.Graph{
		Schema: graph.SchemaVersion, Enterprise: "acme<b>x</b>", CollectedAt: now,
		Nodes: []graph.Node{
			{ID: "org:acme<b>evil</b>", Kind: graph.KindOrg, Name: "acme<b>evil</b>", Evidence: graph.Live,
				Attrs: map[string]string{graph.AttrDefaultPerm: "write"}},
			{ID: "identity:alice<b>", Kind: graph.KindIdentity, Name: "alice<b>", Evidence: graph.Live},
			{ID: "repo:acme-app/<b>web</b>", Kind: graph.KindRepo, Name: "<b>web</b>", Evidence: graph.Live},
		},
		Edges: []graph.Edge{{From: "identity:alice<b>", To: "repo:acme-app/<b>web</b>", Kind: graph.CanPush,
			Evidence: graph.Live, SourceAPI: "rest:<script>alert(1)</script>", ObservedAt: now}},
		Coverage: []graph.Coverage{{Scope: "org:<b>x</b>", Fact: "repositories", Reason: "<i>r</i>", NeedsFix: "<b>fix</b>"}},
	}
	html := render(t, g, "html")
	if strings.Contains(html, "<b>") || strings.Contains(html, "<i>") || strings.Contains(html, "<script>alert") {
		t.Error("HTML did not escape node values")
	}
	assertOnlyOwnScripts(t, html)
	if raw := embeddedJSON(t, html); strings.ContainsAny(raw, "<>") {
		t.Error("embedded JSON holds a raw < or >")
	}
	if !strings.Contains(html, "&lt;b&gt;") {
		t.Error("HTML should contain the escaped name")
	}
	md := render(t, g, "md")
	if strings.Contains(md, "<b>") || strings.Contains(md, "<script") {
		t.Error("MD did not escape node values")
	}
}

func TestRenderEmptyAndBadFormat(t *testing.T) {
	g := &graph.Graph{Schema: graph.SchemaVersion}
	if out := render(t, g, "html"); !strings.Contains(out, "No principal has confirmed reach") {
		t.Error("empty graph headline missing")
	}
	if err := Render(&bytes.Buffer{}, g, Options{Format: "pdf"}); err == nil {
		t.Error("expected error for unknown format")
	}
}

func TestRenderDemo(t *testing.T) {
	g := demo.Generate(demo.Options{Seed: 1})
	html := render(t, g, "html")
	for _, want := range []string{"<title>[demo data] gop report", "<h1>[demo data] gop:", "Pinned, still reachable",
		"acme-actions/setup@main", "Pinning is not enough: 1 action pinned to a commit SHA still runs"} {
		if !strings.Contains(html, want) {
			t.Errorf("html missing %q", want)
		}
	}
	if md := render(t, g, "md"); !strings.HasPrefix(md, "# [demo data] gop:") {
		t.Errorf("md title: %q", md[:60])
	}
	for _, f := range []string{"html", "md"} {
		if out := render(t, loadAcme(t), f); strings.Contains(out, "[demo data]") || strings.Contains(out, "Pinned, still reachable") {
			t.Errorf("%s: non-demo fixture marked as demo or shows a pinned exposure", f)
		}
	}
}

// Owners with identical reach share one row and the headline names the
// group, not one owner picked by tie-break.
func TestRenderGroupsIdenticalReach(t *testing.T) {
	g, err := graph.LoadFile("../../testdata/owners/graph.json")
	if err != nil {
		t.Fatal(err)
	}
	md := render(t, g, "md")
	for _, want := range []string{
		"> The 14 owners of acme-security can push code that runs in 3 repos across 1 org (confirmed)",
		"| 14 principals (org owners of acme-security): identity:owner01, identity:owner02, identity:owner03 and 11 more | 3 | 1 | 1 | 1 | 0 |",
		"| identity:alice | 3 | 2 |", "| identity:bob | 2 | 1 |", "| identity:carol | 2 | 1 |",
		"### identity:owner01, one of 14 principals (org owners of acme-security)",
	} {
		if !strings.Contains(md, want) {
			t.Errorf("markdown lacks %q", want)
		}
	}
	if strings.Contains(md, "identity:owner04") {
		t.Error("markdown should truncate the member list")
	}
	h := render(t, g, "html")
	for _, want := range []string{
		"The 14 owners of acme-security can push code",
		`<span class="grp">14 principals (org owners of acme-security)</span> <code>identity:owner01, identity:owner02, identity:owner03 and 11 more</code>`,
		`<h3><code>identity:owner01</code> <span class="src">one of 14 principals (org owners of acme-security)</span>`,
	} {
		if !strings.Contains(h, want) {
			t.Errorf("html lacks %q", want)
		}
	}
}
