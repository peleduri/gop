func loadAcme(t *testing.T) *graph.Graph {
	t.Helper()
	g, err := graph.LoadFile("../../testdata/acme/graph.json")
	if err != nil {
		t.Fatal(err)
	}
	return g
}

func render(t *testing.T, g *graph.Graph, format string) string {
	t.Helper()
	var buf bytes.Buffer
	if err := Render(&buf, g, Options{Format: format, Version: "v0.0.0-test"}); err != nil {
		t.Fatal(err)
	}
	return buf.String()
}

func TestRenderHTML(t *testing.T) {
	out := render(t, loadAcme(t), "html")
	for _, want := range []string{
		"Members of acme-actions can push code that runs in 12 repos across 2 orgs (confirmed)",
		"Pin acme-actions/deploy@main to a commit SHA",
		"members:acme-legacy", // the legacy principal's possible path is shown
		"possible: a hop is not visible",
		`<span class="badge nv"><span aria-hidden="true">?</span> not visible</span>`,
		"org owner on acme-legacy",
		"Generated by gop v0.0.0-test. This file maps attack paths in your organization. Treat it as sensitive.",
		"prefers-color-scheme: dark",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("HTML missing %q", want)
		}
	}
	lower := strings.ToLower(withoutSVGNS(out))
	for _, bad := range []string{"<link", "src=", "@import", "http://", "https://"} {
		if strings.Contains(lower, bad) {
			t.Errorf("HTML must be self-contained, found %q", bad)
		}
	}
	assertOnlyOwnScripts(t, out)
	// The legacy org's ip_allow_list is "unknown": shown as not visible, never off.
	if strings.Contains(lower, ">off<") {
		t.Error("HTML shows a setting as off")
	}
}

// svgNS is the SVG namespace the Graph tab passes to createElementNS. It is
// an XML namespace name, never fetched; it is the only URL-shaped string the
// report may contain, and only inside the inline script.
const svgNS = "http://www.w3.org/2000/svg"

// withoutSVGNS drops the namespace name from the inline script so the
// no-URL checks still catch any real URL.
func withoutSVGNS(s string) string {
	if strings.Count(scriptJS, svgNS) != 1 {
		return s // the namespace must be one named constant in the script; checks then fail loudly
	}
	return strings.Replace(s, `"`+svgNS+`"`, `""`, 1)
}

