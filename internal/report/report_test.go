package report

import (
	"bytes"
	"strings"
	"testing"
	"time"

	"github.com/peleduri/gop/internal/graph"
)

func loadAcme(t *testing.T) *graph.Graph {
	t.Helper()
	g, err := graph.LoadFile("../../testdata/acme/graph.json")
	if err != nil {
		t.Fatal(err)
	}
	return g
}

func render(t *testing.T, g *graph.Graph, format string) string {
	t.Helper()
	var buf bytes.Buffer
	if err := Render(&buf, g, Options{Format: format, Version: "v0.0.0-test"}); err != nil {
		t.Fatal(err)
	}
	return buf.String()
}

func TestRenderHTML(t *testing.T) {
	out := render(t, loadAcme(t), "html")
	for _, want := range []string{
		"Members of acme-actions can push code that runs in 12 repos across 2 orgs (confirmed)",
		"Pin acme-actions/deploy@main to a commit SHA",
		"members:acme-legacy", // the legacy principal's possible path is shown
		"possible: a hop is not visible",
		`<span class="badge nv">not visible</span>`,
		"org owner on acme-legacy",
		"Generated by gop v0.0.0-test. This file maps attack paths in your organization. Treat it as sensitive.",
		"prefers-color-scheme: dark",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("HTML missing %q", want)
		}
	}
	lower := strings.ToLower(out)
	for _, bad := range []string{"<script", "<link", "src=", "@import", "http://", "https://"} {
		if strings.Contains(lower, bad) {
			t.Errorf("HTML must be self-contained, found %q", bad)
		}
	}
	// The legacy org's ip_allow_list is "unknown": shown as not visible, never off.
	if strings.Contains(lower, ">off<") {
		t.Error("HTML shows a setting as off")
	}
}

func TestRenderMarkdown(t *testing.T) {
	out := render(t, loadAcme(t), "md")
	for _, want := range []string{
		"# gop: who can make code run where",
		"| members:acme-actions | 12 | 2 |",
		"not visible",
		"Treat it as sensitive.",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("MD missing %q", want)
		}
	}
	if strings.Contains(strings.ToLower(out), "<script") {
		t.Error("MD contains a script tag")
	}
}

func TestRenderEscapes(t *testing.T) {
	now := time.Date(2026, 11, 20, 10, 0, 0, 0, time.UTC)
	g := &graph.Graph{
		Schema: graph.SchemaVersion, Enterprise: "acme<b>x</b>", CollectedAt: now,
		Nodes: []graph.Node{
			{ID: "org:acme<b>evil</b>", Kind: graph.KindOrg, Name: "acme<b>evil</b>", Evidence: graph.Live,
				Attrs: map[string]string{graph.AttrDefaultPerm: "write"}},
			{ID: "identity:alice<b>", Kind: graph.KindIdentity, Name: "alice<b>", Evidence: graph.Live},
			{ID: "repo:acme-app/<b>web</b>", Kind: graph.KindRepo, Name: "<b>web</b>", Evidence: graph.Live},
		},
		Edges: []graph.Edge{{From: "identity:alice<b>", To: "repo:acme-app/<b>web</b>", Kind: graph.CanPush,
			Evidence: graph.Live, SourceAPI: "rest:<script>alert(1)</script>", ObservedAt: now}},
		Coverage: []graph.Coverage{{Scope: "org:<b>x</b>", Fact: "repositories", Reason: "<i>r</i>", NeedsFix: "<b>fix</b>"}},
	}
	html := render(t, g, "html")
	if strings.Contains(html, "<b>") || strings.Contains(html, "<script") || strings.Contains(html, "<i>") {
		t.Error("HTML did not escape node values")
	}
	if !strings.Contains(html, "&lt;b&gt;") {
		t.Error("HTML should contain the escaped name")
	}
	md := render(t, g, "md")
	if strings.Contains(md, "<b>") || strings.Contains(md, "<script") {
		t.Error("MD did not escape node values")
	}
}

func TestRenderEmptyAndBadFormat(t *testing.T) {
	g := &graph.Graph{Schema: graph.SchemaVersion}
	if out := render(t, g, "html"); !strings.Contains(out, "No principal has confirmed reach") {
		t.Error("empty graph headline missing")
	}
	if err := Render(&bytes.Buffer{}, g, Options{Format: "pdf"}); err == nil {
		t.Error("expected error for unknown format")
	}
}
