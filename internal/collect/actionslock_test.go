const (
	lockWebCI    = "workflow:acme-app/web/.github/workflows/ci.yml"
	lockCheckout = "action:actions/checkout@v4"
	lockDeploy   = "action:acme-actions/deploy@main"
	lockFile     = "acme-app/web/actions.lock"
)

// webLock is a synthetic lockfile for acme-app/web. Its ci.yml uses
// actions/checkout@v4 and acme-actions/deploy@main; deploy@main runs
// setup@main, which runs checkout@v4 and deploy@<testSHA>. pins lists the
// ci.yml entry; every pin gets a dependency entry.
func webLock(pins ...string) string {
	var b strings.Builder
	b.WriteString("# This file is machine-generated by `gh actions-lock`.\nversion: 'v0.0.3'\nworkflows:\n  '.github/workflows/ci.yml':\n")
	for _, p := range pins {
		b.WriteString("    - '" + p + "'\n")
	}
	b.WriteString("dependencies:\n")
	for i, p := range pins {
		_, ref, _ := strings.Cut(p, "@")
		b.WriteString("  '" + p + "':\n    ref: '" + ref + "'\n    commit: 'sha1-" + strings.Repeat(string("abcdef"[i%6]), 40) + "'\n    owner_id: 1\n    repo_id: " + string(rune('1'+i)) + "\n")
	}
	return b.String()
}

var fullLock = []string{"actions/checkout@v4", "acme-actions/deploy@main", "acme-actions/setup@main", "acme-actions/deploy@" + testSHA}

// collectLock collects the fixture with lock planted as acme-app/web's
// actions.lock (none when empty), over REST and batched GraphQL, and checks
// both give the same graph.
func collectLock(t *testing.T, lock string) *graph.Graph {
	t.Helper()
	var out []*graph.Graph
	for _, batch := range []bool{false, true} {
		f := newFakeGitHub(t)
		if lock != "" {
			f.extraWorkflows[lockFile] = lock
		}
		g, err := Collect(context.Background(), Config{Enterprise: "acme", Client: f.client(t), DisableGraphQLBatch: !batch})
		if err != nil {
			t.Fatal(err)
		}
		out = append(out, g)
	}
	if a, b := normalized(t, out[0]), normalized(t, out[1]); a != b {
		t.Fatal("batched graph differs from REST with an actions.lock")
	}
	return out[0]
}

// actionHopInto reports whether some principal's path to wf enters it
// through an action (a reversed USES hop).
func actionHopInto(g *graph.Graph, wf string) bool {
	ix := graph.NewIndex(g)
	for _, p := range ix.Principals() {
		path, ok := ix.Reach(p, graph.Options{}).Paths[wf]
		if !ok {
			continue
		}
		for _, h := range path.Hops {
			if h.Kind == graph.Uses && h.To == wf {
				return true
			}
		}
	}
	return false
}

func TestActionsLockNone(t *testing.T) {
	g := collectLock(t, "")
	ix := newIndex(g)
	if v, ok := ix.node(t, "repo:acme-app/web").Attrs[graph.AttrActionsLock]; ok {
		t.Errorf("repo without a lockfile has actions_lock=%q", v)
	}
	for _, to := range []string{lockCheckout, lockDeploy} {
		if e := ix.mustEdge(t, lockWebCI, to, graph.Uses); e.Attrs[graph.AttrActionsLock] != "" {
			t.Errorf("%s: actions_lock=%q without a lockfile", to, e.Attrs[graph.AttrActionsLock])
		}
	}
	if !actionHopInto(g, lockWebCI) {
		t.Fatal("fixture: expected a path into web ci.yml through deploy@main without a lockfile")
	}
}

func TestActionsLockLocked(t *testing.T) {
	g := collectLock(t, webLock(fullLock...))
	ix := newIndex(g)
	if v := ix.node(t, "repo:acme-app/web").Attrs[graph.AttrActionsLock]; v != "true" {
		t.Errorf("repo actions_lock=%q, want true", v)
	}
	co := ix.mustEdge(t, lockWebCI, lockCheckout, graph.Uses)
	if co.Attrs[graph.AttrActionsLock] != graph.LockLocked || co.Attrs[graph.AttrLockedSHA] != strings.Repeat("a", 40) {
		t.Errorf("checkout edge attrs %v", co.Attrs)
	}
	// deploy@main is locked only because the lock also pins the nested
	// setup@main (and what setup runs), which no workflow file pins.
	de := ix.mustEdge(t, lockWebCI, lockDeploy, graph.Uses)
	if de.Attrs[graph.AttrActionsLock] != graph.LockLocked || de.Attrs[graph.AttrLockedSHA] != strings.Repeat("b", 40) {
		t.Errorf("deploy edge attrs %v", de.Attrs)
	}
	// Other repos' uses of the same actions are untouched.
	if e := ix.mustEdge(t, "workflow:acme-app/billing/.github/workflows/deploy.yml", lockDeploy, graph.Uses); e.Attrs[graph.AttrActionsLock] != "" {
		t.Errorf("billing deploy.yml edge got actions_lock=%q from web's lockfile", e.Attrs[graph.AttrActionsLock])
	}
	if actionHopInto(g, lockWebCI) {
		t.Error("a path still enters web ci.yml through a locked action")
	}
	st := graph.NewIndex(g).PinStats()
	if st.ByLock != 2 || st.Locks != 1 || st.Stale != 0 {
		t.Errorf("pin stats %+v", st)
	}
	for _, c := range g.Coverage {
		if strings.HasPrefix(c.Fact, graph.AttrActionsLock) {
			t.Errorf("unexpected coverage %+v", c)
		}
	}
}

func TestActionsLockNestedMissing(t *testing.T) {
	// The lock pins deploy@main but not the nested setup@main.
	g := collectLock(t, webLock("actions/checkout@v4", "acme-actions/deploy@main", "acme-actions/deploy@"+testSHA))
	ix := newIndex(g)
	de := ix.mustEdge(t, lockWebCI, lockDeploy, graph.Uses)
	if de.Attrs[graph.AttrActionsLock] != graph.LockStale || de.Attrs[graph.AttrLockMissing] != "acme-actions/setup@main" || de.Attrs[graph.AttrLockedSHA] != "" {
		t.Errorf("deploy edge attrs %v", de.Attrs)
	}
	if co := ix.mustEdge(t, lockWebCI, lockCheckout, graph.Uses); co.Attrs[graph.AttrActionsLock] != graph.LockLocked {
		t.Errorf("checkout edge attrs %v", co.Attrs)
	}
	c, ok := hasCoverage(g, lockWebCI, "actions_lock:acme-actions/deploy@main")
	if !ok || !strings.Contains(c.Reason, "nested acme-actions/setup@main") || !strings.Contains(c.NeedsFix, "gh actions-lock") {
		t.Errorf("coverage %+v %v", c, ok)
	}
	if !actionHopInto(g, lockWebCI) {
		t.Error("a stale lock must not block the path through deploy@main")
	}
}

func TestActionsLockStaleRef(t *testing.T) {
	// The workflow says checkout@v4; the lock still pins checkout@v3.
	g := collectLock(t, webLock("actions/checkout@v3", "acme-actions/deploy@main", "acme-actions/setup@main", "acme-actions/deploy@"+testSHA))
	ix := newIndex(g)
	co := ix.mustEdge(t, lockWebCI, lockCheckout, graph.Uses)
	if co.Attrs[graph.AttrActionsLock] != graph.LockStale || co.Attrs[graph.AttrLockEntry] != "actions/checkout@v3" {
		t.Errorf("checkout edge attrs %v", co.Attrs)
	}
	c, ok := hasCoverage(g, lockWebCI, "actions_lock:actions/checkout@v4")
	if !ok || !strings.Contains(c.Reason, "pins actions/checkout@v3 but the workflow uses actions/checkout@v4") {
		t.Errorf("coverage %+v %v", c, ok)
	}
	// setup@main, nested under deploy@main, runs checkout@v4 too, which the
	// lock does not pin: deploy@main is stale as well.
	de := ix.mustEdge(t, lockWebCI, lockDeploy, graph.Uses)
	if de.Attrs[graph.AttrActionsLock] != graph.LockStale || de.Attrs[graph.AttrLockMissing] != "actions/checkout@v4" {
		t.Errorf("deploy edge attrs %v", de.Attrs)
	}
	st := graph.NewIndex(g).PinStats()
	if st.Stale != 2 || st.ByLock != 0 {
		t.Errorf("pin stats %+v", st)
	}
}

